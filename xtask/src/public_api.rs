//! `cargo xtask public-api [--check]`: the public-API snapshot of `persia` (ROADMAP 10.1.12; ADR-0063 item 10,
//! amended).
//!
//! Builds rustdoc's JSON (an unstable output, so with the dated nightly of `.github/nightly-toolchain`, as Miri and the
//! fuzz targets use) for `persia` with the features a user can enable (`async`; not `internal` or `test-hooks`, which
//! are hidden and unstable), and for the workspace crates it re-exports from, then renders the surface as sorted lines
//! ([`render`]) with the re-exported engine items expanded. Without `--check` it writes
//! `crates/persia/public-api.txt`; with it, it fails when the file differs, listing the lines added and removed: a
//! change of the public surface must come with the regenerated file, so a reviewer sees it.

mod render;

use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};

pub use render::{Crate, Crates, render};

/// The committed snapshot, relative to the repository root.
pub const SNAPSHOT: &str = "crates/persia/public-api.txt";

/// The features of `persia` the snapshot covers: those a user can enable and rely on.
const FEATURES: &str = "async";

/// The workspace crates `persia` re-exports items from (directly, or through one of them): their JSON expands the
/// re-exports.
const SOURCES: [&str; 4] = [
    "persia-engine",
    "persia-blob",
    "persia-format",
    "persia-analysis",
];

const HEADER: &str = "# The public API of `persia` with the feature `async` (ROADMAP 10.1.12): generated by `cargo xtask public-api`\n# (`just public-api`) from rustdoc's JSON. Do not edit; regenerate it with the change that moves the surface.\n";

pub fn run(root: &Path, args: &[String]) -> Result<bool> {
    let check = check_mode(args)?;
    let rendered = format!("{HEADER}{}", render(&build(root)?)?);
    let path = root.join(SNAPSHOT);
    if check {
        let committed = std::fs::read_to_string(&path)
            .with_context(|| format!("reading {}", path.display()))?;
        match diff(&committed, &rendered) {
            None => {
                println!("{SNAPSHOT} is up to date");
                Ok(true)
            }
            Some(report) => {
                eprintln!(
                    "the public API of persia changed without {SNAPSHOT}: run `just public-api` and commit it\n{report}"
                );
                Ok(false)
            }
        }
    } else {
        std::fs::write(&path, rendered).with_context(|| format!("writing {}", path.display()))?;
        println!("wrote {SNAPSHOT}");
        Ok(true)
    }
}

/// Whether `args` ask for `--check` (else the file is written).
///
/// # Errors
/// Arguments other than none or `--check`.
fn check_mode(args: &[String]) -> Result<bool> {
    match args {
        [] => Ok(false),
        [flag] if flag == "--check" => Ok(true),
        _ => bail!("usage: cargo xtask public-api [--check]"),
    }
}

/// The lines `rendered` adds to `committed` (`+`) and removes from it (`-`), or `None` when the two are equal.
pub fn diff(committed: &str, rendered: &str) -> Option<String> {
    if committed == rendered {
        return None;
    }
    let old: std::collections::BTreeSet<&str> = committed.lines().collect();
    let new: std::collections::BTreeSet<&str> = rendered.lines().collect();
    let mut report = String::new();
    for line in new.difference(&old) {
        report.push_str("+ ");
        report.push_str(line);
        report.push('\n');
    }
    for line in old.difference(&new) {
        report.push_str("- ");
        report.push_str(line);
        report.push('\n');
    }
    if report.is_empty() {
        // The same lines, in another order or repeated: the file was not written by this command.
        report.push_str("(the same lines in another order: regenerate the file)\n");
    }
    Some(report)
}

/// The dated nightly of `.github/nightly-toolchain`.
fn nightly(root: &Path) -> Result<String> {
    let text = std::fs::read_to_string(root.join(".github/nightly-toolchain"))
        .context("reading .github/nightly-toolchain")?;
    let nightly = text.trim();
    if nightly.is_empty() {
        bail!(".github/nightly-toolchain is empty");
    }
    Ok(nightly.to_owned())
}

/// rustdoc's JSON of `persia` and [`SOURCES`], built into a target directory of its own (the nightly's artifacts
/// stay apart from the pinned toolchain's).
fn build(root: &Path) -> Result<Crates> {
    let nightly = nightly(root)?;
    let target = root.join("target/public-api");
    // Two runs: `--features persia/async` beside other packages is not applied to `persia` by `cargo doc --no-deps`.
    let sources: Vec<&str> = SOURCES.iter().flat_map(|c| ["-p", *c]).collect();
    for packages in [vec!["-p", "persia", "--features", FEATURES], sources] {
        let status = Command::new("cargo")
            .current_dir(root)
            .arg(format!("+{nightly}"))
            .args(["doc", "--no-deps", "--locked"])
            .args(&packages)
            .env("CARGO_TARGET_DIR", &target)
            .env("RUSTDOCFLAGS", "-Z unstable-options --output-format json")
            // The toolchain is chosen on the command line; a pinned one in the environment must not win.
            .env_remove("RUSTUP_TOOLCHAIN")
            .status()
            .with_context(|| {
                format!("running cargo +{nightly} doc (is the toolchain installed?)")
            })?;
        if !status.success() {
            bail!(
                "cargo +{nightly} doc {} failed: {status}",
                packages.join(" ")
            );
        }
    }
    let read = |name: &str| -> Result<Crate> {
        let file: PathBuf = target
            .join("doc")
            .join(format!("{}.json", name.replace('-', "_")));
        let text = std::fs::read_to_string(&file)
            .with_context(|| format!("reading {}", file.display()))?;
        Crate::parse(&text).with_context(|| file.display().to_string())
    };
    let others = SOURCES
        .iter()
        .map(|c| read(c))
        .collect::<Result<Vec<_>>>()?;
    Crates::new(read("persia")?, others)
}

